"""Generate anti-aliased bitmap fonts for nnr_esp from IBM Plex Sans Thai.

Run with a Python that has Pillow (11.x):

    python tools/make_fonts.py fonts/ src/aa_fonts.h

Each glyph is rendered at its pixel size and stored as 4-bit coverage (16
levels), with its offset from the pen position on the baseline and its
advance in 1/16 px. The firmware blends these onto the framebuffer.

Thai marks (upper/lower vowels, tone marks) have zero advance and sit to the
left of the pen, so drawing them after their base letter overlays them. The
font positions a tone mark over an upper vowel, and marks over the tall
letters, with OpenType rules the panel does not run; instead this script
measures, per size, how far to lift such a tone mark, and where the tail of
the tall letters (ป ฝ ฟ ฬ) starts so each mark can be shifted just clear of it.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ASCII = list(range(0x20, 0x7F))
THAI = list(range(0x0E01, 0x0E3B)) + list(range(0x0E3F, 0x0E5C))
EXTRA = [0x00B0, 0x00B3, 0x00B5, 0x00B7, 0x2013, 0x2014, 0x2026, 0x2192]  # ° ³ µ · – — … →

# name, file, pixel size, character set
STYLES = [
    ("caps11", "IBMPlexSansThai-SemiBold.ttf", 11, ASCII + THAI + EXTRA),  # small uppercase labels
    ("text12", "IBMPlexSansThai-Regular.ttf", 12, ASCII + THAI + EXTRA),   # size 1 text
    ("body15", "IBMPlexSansThai-Regular.ttf", 15, ASCII + THAI + EXTRA),   # body / Thai text
    ("title17", "IBMPlexSansThai-SemiBold.ttf", 17, ASCII + THAI + EXTRA), # size 2
    ("head22", "IBMPlexSansThai-SemiBold.ttf", 22, ASCII + THAI + EXTRA),  # size 3
    ("num30", "IBMPlexSansThai-SemiBold.ttf", 30, ASCII + [0x0E3F, 0x00B0]),  # size 4: numbers
    ("clock64", "IBMPlexSansThai-SemiBold.ttf", 64, [ord(c) for c in " 0123456789:-"]),  # size 5: world clock, AQI
]

UPPER_VOWELS = [0x0E31, 0x0E34, 0x0E35, 0x0E36, 0x0E37, 0x0E47]
TONES = [0x0E48, 0x0E49, 0x0E4A, 0x0E4B, 0x0E4C]
TALL = [0x0E1B, 0x0E1D, 0x0E1F, 0x0E2C]


def glyph(font, cp):
    """Coverage bitmap (rows of 0..255), offset (x, y from baseline) and advance."""
    ch = chr(cp)
    adv = font.getlength(ch)
    bbox = font.getbbox(ch, anchor="ls")  # relative to the pen on the baseline
    if bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
        return [], 0, 0, adv
    x0, y0, x1, y1 = bbox
    pad = 2
    img = Image.new("L", (x1 - x0 + 2 * pad, y1 - y0 + 2 * pad), 0)
    ImageDraw.Draw(img).text((pad - x0, pad - y0), ch, font=font, fill=255, anchor="ls")
    px = img.load()
    w, h = img.size
    rows = [[px[x, y] for x in range(w)] for y in range(h)]
    # trim empty borders
    while rows and not any(rows[0]): rows.pop(0); y0 += 1
    while rows and not any(rows[-1]): rows.pop()
    if not rows:
        return [], 0, 0, adv
    left = min(next(i for i, v in enumerate(r) if v) for r in rows if any(r))
    right = max(len(r) - next(i for i, v in enumerate(reversed(r)) if v) for r in rows if any(r))
    rows = [r[left:right] for r in rows]
    return rows, x0 - pad + left, y0 - pad, adv


def ink_rows(rows, oy):
    """Top and bottom ink row (baseline-relative) of a bitmap."""
    return oy, oy + len(rows) - 1


def measure(font):
    """Tone lift over upper vowels, and the tall letters' tail column.

    tailX is the leftmost column of ป's tail (any visible ink) relative to the
    pen *after* the letter, which is where its marks are drawn from. A mark
    whose right edge reaches tailX is moved left until it clears it.
    """
    lift = 0
    for v in UPPER_VOWELS:
        vrows, vx, vy, _ = glyph(font, v)
        if not vrows:
            continue
        for t in TONES:
            trows, tx, ty, _ = glyph(font, t)
            if trows:
                lift = max(lift, (ty + len(trows) - 1) - vy + 2)
    rows, bx, by, badv = glyph(font, 0x0E1B)  # ป: its first rows are only the tail
    tail = min(min(i for i, v in enumerate(r) if v > 32) for r in rows[:2])
    return max(0, lift), bx + tail - round(badv)


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    lines = [
        "// Generated by tools/make_fonts.py from IBM Plex Sans Thai (SIL OFL 1.1,",
        "// see fonts/OFL.txt). Do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct AAGlyph { uint32_t cp; uint32_t offset; uint8_t w, h; int8_t x, y; uint16_t adv16; };",
        "struct AAFont {",
        "    const AAGlyph *glyphs; uint16_t count; const uint8_t *bits;",
        "    int8_t capHeight, ascent, descent;  // px above/below the baseline",
        "    int8_t toneLift, tailX;            // Thai mark adjustments for this size",
        "};",
        "",
    ]
    total = 0
    for name, file, size, charset in STYLES:
        font = ImageFont.truetype(str(src / file), size)
        glyphs, bits = [], bytearray()
        for cp in sorted(set(charset)):
            rows, ox, oy, adv = glyph(font, cp)
            h = len(rows)
            w = len(rows[0]) if rows else 0
            offset = len(bits)
            nibbles = [min(15, (v + 8) // 17) for r in rows for v in r]
            if len(nibbles) % 2:
                nibbles.append(0)
            bits += bytes((nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2))
            glyphs.append((cp, offset, w, h, ox, oy, round(adv * 16)))
        cap = -glyph(font, ord("H"))[2]
        asc, desc = font.getmetrics()
        lift, shift = measure(font) if 0x0E48 in charset else (0, 127)
        lines.append(f"static const uint8_t {name}_bits[] = {{")
        for i in range(0, len(bits), 24):
            lines.append("    " + ",".join(str(b) for b in bits[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const AAGlyph {name}_glyphs[] = {{")
        for g in glyphs:
            lines.append("    {0x%04X,%d,%d,%d,%d,%d,%d}," % g)
        lines.append("};")
        lines.append(f"static const AAFont {name} = {{{name}_glyphs, {len(glyphs)}, {name}_bits, "
                     f"{cap}, {asc}, {desc}, {lift}, {shift}}};")
        lines.append("")
        total += len(bits) + len(glyphs) * 16
        print(f"{name}: {len(glyphs)} glyphs, {len(bits)} bytes, cap {cap}, tone lift {lift}, tail x {shift}")
    out.write_text("\n".join(lines) + "\n")
    print(f"total ~{total // 1024} KB -> {out}")


if __name__ == "__main__":
    main()
